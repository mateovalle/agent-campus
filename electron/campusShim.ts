/**
 * Putting `campus` on an agent's PATH without requiring node.
 *
 * The app ships Electron, not node — but Electron with ELECTRON_RUN_AS_NODE=1
 * IS node, so the shim execs our own binary on the compiled CLI. Both paths
 * are absolute and baked in at launch, which is also the self-healing story:
 * an app that was moved, reinstalled or upgraded leaves a shim pointing at a
 * binary that no longer exists, and the next launch simply rewrites it.
 *
 * The CLI is COPIED OUT of the asar first. Reading out of an asar archive is
 * well supported; executing a script from inside one depends on whether
 * ELECTRON_RUN_AS_NODE keeps the asar fs patch installed, which is an
 * undocumented detail not worth betting the feature on.
 */

import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';

import { DATA_DIR_NAME } from '../src/core/constants.js';

/**
 * The CLI's whole runtime graph. Node builtins aside, campusCli.js requires
 * exactly one local module, so both files have to come out of the asar
 * together — copying only the entry point produces a shim that installs
 * cleanly, looks right on disk, and dies with MODULE_NOT_FOUND the first time
 * an agent actually calls it.
 */
const CLI_RUNTIME_FILES = ['campusCli.js', 'campusServer.js'] as const;

/** Lazy, like every other data path here, so an isolated HOME is honoured. */
export function campusBinDir(): string {
  return path.join(os.homedir(), DATA_DIR_NAME, 'bin');
}

/**
 * Quotes a path for POSIX sh. The macOS target is literally
 * `/Applications/Agent Campus.app/Contents/MacOS/Agent Campus` — spaces are
 * guaranteed, and an apostrophe in a user's home directory is not exotic.
 */
export function shSingleQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

/**
 * The POSIX shim. `exec` so exit codes and signals pass straight through, and
 * the `VAR=value exec` form scopes ELECTRON_RUN_AS_NODE to this one process
 * so it cannot leak into anything the CLI itself starts. `"$@"` (never `$*`)
 * keeps `campus status "two words"` a single argument.
 */
export function renderPosixShim(o: { electron: string; cli: string; stamp: string }): string {
  return [
    '#!/bin/sh',
    `# Generated by Agent Campus ${o.stamp}. Rewritten on every launch — do not edit.`,
    `ELECTRON_RUN_AS_NODE=1 exec ${shSingleQuote(o.electron)} ${shSingleQuote(o.cli)} "$@"`,
    '',
  ].join('\n');
}

/**
 * The Windows shim. `%*` is lossy for `& | < > ^ %` — a documented limit, not
 * a bug worth a PowerShell wrapper (whose default execution policy would
 * block it anyway).
 */
export function renderWindowsShim(o: { electron: string; cli: string; stamp: string }): string {
  return [
    '@echo off',
    `REM Generated by Agent Campus ${o.stamp}. Rewritten on every launch — do not edit.`,
    'setlocal',
    'set "ELECTRON_RUN_AS_NODE=1"',
    `"${o.electron}" "${o.cli}" %*`,
    'endlocal & exit /b %ERRORLEVEL%',
    '',
  ].join('\n');
}

/** Writes via a temp file + rename: a plain overwrite of a script another
 * process is mid-exec on gives ETXTBSY or a half-read script; a rename swaps
 * the inode and leaves the running copy alone. */
function writeExecutable(target: string, contents: string): void {
  const tmp = `${target}.tmp`;
  fs.writeFileSync(tmp, contents, { mode: 0o755 });
  fs.renameSync(tmp, target);
}

export interface CampusShims {
  binDir: string;
  /** Absolute path of the POSIX shim, for scripts that want it directly. */
  campus: string;
}

/**
 * Installs the shims and the CLI into ~/.pixel-agents/bin, returning null if
 * anything fails — the office works fine without them, so an unwritable home
 * directory must not stop a launch.
 *
 * `cliSource` points at the compiled campusCli.js (inside the asar when
 * packaged); everything in CLI_RUNTIME_FILES is taken from beside it.
 */
export function installCampusShims(opts: {
  electronPath: string;
  cliSource: string;
  version: string;
}): CampusShims | null {
  try {
    const binDir = campusBinDir();
    fs.mkdirSync(binDir, { recursive: true, mode: 0o700 });

    const sourceDir = path.dirname(opts.cliSource);
    for (const file of CLI_RUNTIME_FILES) {
      fs.copyFileSync(path.join(sourceDir, file), path.join(binDir, file));
    }
    const cli = path.join(binDir, CLI_RUNTIME_FILES[0]);

    const stamp = `${opts.version} ${new Date().toISOString()}`;
    const campus = path.join(binDir, 'campus');
    writeExecutable(campus, renderPosixShim({ electron: opts.electronPath, cli, stamp }));
    // Written on every platform: a Windows user with git-bash gets a working
    // `campus` too, and it costs one file.
    writeExecutable(
      path.join(binDir, 'campus.cmd'),
      renderWindowsShim({ electron: opts.electronPath, cli, stamp }),
    );
    return { binDir, campus };
  } catch (err) {
    console.error('[Agent Campus] Could not install the campus CLI:', err);
    return null;
  }
}
